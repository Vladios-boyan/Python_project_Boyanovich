#Условие: Мастям игральных карт присвоены порядковые номера: 1 — пики, 2 — трефы, 3 — бубны, 4 — червы.
# Достоинству карт, старших десятки, присвоены номера: 11 — валет, 12 — дама, 13 — король, 14 — туз. Дано трехзначное число, в котором
# первая цифра указывает на масть, а вторые две на достоинство карты. Вывести соответствующее название карты вида «дама червей», «туз треф» и т.п.

# Запуск бесконечного цикла для ввода и проверки правильности карты
while True:
    # 1. Защита от букв и проверка на трехзначное число
    k = input("Введите трехзначное число (например - 412): ")
    try:
        k = int(k)
        if 100 <= k <= 999:
            # Если число трехзначное, продолжаем проверку
            pass
        else:
            print("Ошибка: число должно быть трехзначным! Попробуйте снова.")
            continue  # Возвращаемся в начало цикла
    except ValueError:
        print("Ошибка: вы ввели не число. Попробуйте снова.")
        continue  # Возвращаемся в начало цикла

    # 2. Разделяем число на масть и достоинство
    first_num = k // 100
    rank_numb = k % 100

    # 3. Проверяем масть (от 1 до 4)
    if first_num == 1:
        first_name = "Пик"
    elif first_num == 2:
        first_name = "Треф"
    elif first_num == 3:
        first_name = "Бубны"
    elif first_num == 4:
        first_name = "Черви"
    else:
        print("Неизвестная масть! Введите правильный код карты заново.")
        continue  # Если масть неверная — цикл начинается с самого начала

    # 4. Проверяем достоинство (от 6 до 10, или валет/дама/король/туз: 11-14)
    if rank_numb == 11:
        rank_name = "Валет"
    elif rank_numb == 12:
        rank_name = "Дама"
    elif rank_numb == 13:
        rank_name = "Король"
    elif rank_numb == 14:
        rank_name = "Туз"
    elif 6 <= rank_numb <= 10:
        rank_name = str(rank_numb)
    else:
        print("Неизвестное достоинство карты! Введите код заново.")
        continue  # Если достоинство неверное — цикл начинается сначала

    # Если всё прошло успешно — выводим результат и выходим из цикла (break)
    print(f"Карта: {rank_name} {first_name}")
    break







